  pass('overlapping Rylie and horse hours enable online bookings')

  await addHours('', '05:15', '05:45', false)
  await page.getByText(/Time window overlaps with existing/).waitFor()
  await day(0).getByRole('button', { name: 'Cancel', exact: true }).click()
  await addHours('', '07:00', '06:00', false)
  await page.getByText('Start time must be before end time', { exact: true }).last().waitFor()
  await day(0).getByRole('button', { name: 'Cancel', exact: true }).click()
  pass('invalid and overlapping hours are rejected')
  await addHours('', '06:00', '07:00')
  await page.getByText('Availability window added', { exact: true }).last().waitFor()
  await day(0).getByRole('button', { name: 'Remove', exact: true }).last().click()
  await page.getByRole('button', { name: 'Remove', exact: true }).last().click()
  await page.getByText('Availability window removed', { exact: true }).last().waitFor()
